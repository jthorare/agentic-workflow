#!/usr/bin/env bun
// Regenerates src/py/ucd.ts, the Unicode tables the Python-semantics kernel uses instead of the JS engine's own
// (bun's ICU is newer than CPython 3.13's Unicode 15.1, so \p{L} and friends disagree on about 9,000 code points).
// Usage: bun run parity/gen-ucd.ts        (needs python3; the oracle is CPython itself)
import { spawnSync } from "bun";

type Runs = [number, number][];
const here = new URL(".", import.meta.url).pathname;
const r = spawnSync(["python3", "-I", "-B", `${here}oracle.py`, "ucd"], { stdout: "pipe", stderr: "pipe" });
if (r.exitCode !== 0) throw new Error(`oracle ucd failed: ${r.stderr.toString()}`);
const g = JSON.parse(r.stdout.toString()) as {
  unicode: string; python: string; w: Runs; d: Runs; s: Runs; isspace: Runs; isdecimal: Runs; printable: Runs;
  linebreak: Runs; split_ws: Runs; strip_ws: Runs; lower: Record<string, string>; upper: Record<string, string>;
};
const same = (a: Runs, b: Runs) => JSON.stringify(a) === JSON.stringify(b);
for (const [k, v] of [["isspace", g.isspace], ["split_ws", g.split_ws], ["strip_ws", g.strip_ws]] as const)
  if (!same(g.s, v)) throw new Error(`re \\s and ${k} differ in this Python: the kernel assumes one whitespace set`);
if (!same(g.d, g.isdecimal)) throw new Error("re \\d and str.isdecimal differ in this Python");

const enc = (runs: Runs) => runs.map(([a, b]) => (a === b ? a.toString(16) : `${a.toString(16)}-${b.toString(16)}`)).join(",");
const wrap = (s: string) => {
  const out: string[] = [];
  for (let i = 0; i < s.length; i += 112) out.push(JSON.stringify(s.slice(i, i + 112)));
  return out.join(" +\n  ");
};
function exceptions(map: Record<string, string>, js: (s: string) => string): [number, string][] {
  const out: [number, string][] = [];
  for (let c = 0; c < 0x110000; c++) {
    const ch = String.fromCodePoint(c);
    const py = map[String(c)] ?? ch;
    if (js(ch) !== py) out.push([c, py]);
  }
  return out;
}
const lx = exceptions(g.lower, (s) => s.toLowerCase());
const ux = exceptions(g.upper, (s) => s.toUpperCase());
const pairs = (xs: [number, string][]) =>
  xs.map(([c, s]) => `[0x${c.toString(16)}, ${JSON.stringify(s).replace(/[^\x20-\x7e]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`)}]`).join(", ");

const src = `// Generated by parity/gen-ucd.ts from CPython ${g.python} (Unicode ${g.unicode}); do not edit by hand.
// Regenerate with \`bun run parity/gen-ucd.ts\`; test/py/ucd.test.ts checks every table against the live python3.
// Runs are comma-separated hex code points or ranges (inclusive).

export const UNICODE_VERSION = ${JSON.stringify(g.unicode)};
export const PYTHON_VERSION = ${JSON.stringify(g.python)};

/** re \\w for str patterns: ch.isalnum() or ch == "_". */
export const W_RUNS =
  ${wrap(enc(g.w))};

/** re \\d and str.isdecimal() (Unicode Nd). */
export const D_RUNS =
  ${wrap(enc(g.d))};

/** re \\s, str.isspace(), and the separators of split() / strip() with no argument. */
export const S_RUNS = ${JSON.stringify(enc(g.s))};

/** str.isprintable() (what repr() leaves unescaped). */
export const PRINTABLE_RUNS =
  ${wrap(enc(g.printable))};

/** The boundaries of str.splitlines() ("\\r\\n" counts once). */
export const LINEBREAK_RUNS = ${JSON.stringify(enc(g.linebreak))};

/** Code points where CPython's lower() differs from this engine's String.prototype.toLowerCase (newer Unicode). */
export const LOWER_X: ReadonlyArray<readonly [number, string]> = [${pairs(lx)}];

/** Code points where CPython's upper() differs from this engine's String.prototype.toUpperCase. */
export const UPPER_X: ReadonlyArray<readonly [number, string]> = [${pairs(ux)}];
`;
await Bun.write(`${here}../src/py/ucd.ts`, src);
console.log(`wrote src/py/ucd.ts: Unicode ${g.unicode}, \\w ${g.w.length} runs, \\d ${g.d.length}, printable ${g.printable.length}, lower x${lx.length}, upper x${ux.length}`);
