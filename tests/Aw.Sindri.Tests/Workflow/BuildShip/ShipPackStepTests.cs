/// <summary>'step.ship.pack' on the block runtime (line spec §7.5): the hand-off draft, its PR body generated by code from the proof pack, the review result and the phase packet.</summary>
[Lane(TestLane.Unit)]
public sealed class ShipPackStepTests
{
    private const string Address = "T-1/line/1/phase.p1.1/ship.1";
    private const string Tree = "/work/p1";
    private const string Checkout = "/checkouts/name";
    private const string PacketDir = "/packets/demo-p1";
    private const string ProofDir = "/runs/proof-pack";
    private const string ReviewDir = "/runs/review-pack";
    private const string BaseSha = "0123456789abcdef0123456789abcdef01234567";
    private const string Canary = "violet otter ledger 4417";

    private const string SetText = """{ "schemaVersion": 1, "phase": "demo-p1", "scenarios": [ { "id": "H1", "item": "AC-1", "kind": "api", "steps": ["open an expired link"], "expected": "status 410" }, { "id": "C1", "item": null, "kind": "canary", "steps": [], "expected": "never", "phrase": "violet otter ledger 4417" } ] }""";

    private static readonly string[] _linkKeys = ["pr", "body", "green", "index"];

    private static readonly Dictionary<string, string> _baseFacts = new(StringComparer.Ordinal)
    {
        ["phasePacket"] = $$"""{"hash":"sha256:phase","dir":"{{PacketDir}}","base":{"rule":"default-branch","ref":""},"stackParent":null}""",
        ["proofPack"] = $$"""{"hash":"sha256:proof","dir":"{{ProofDir}}","head":"h1"}""",
        ["review"] = $$"""{"hash":"sha256:review","dir":"{{ReviewDir}}","head":"h1"}""",
        ["lineContext"] = $$"""{"line":"demo","phase":"p1","attempt":1,"base":"{{BaseSha}}","runArea":"/runs"}""",
        ["workspace"] = Tree,
        ["green"] = """{"commands":["dotnet build","dotnet test"]}""",
    };

    private static CancellationToken Token => TestContext.Current.CancellationToken;

    private static StepContext Context(Dictionary<string, string>? facts = null, bool address = true, bool repo = true) =>
        BuildShipContexts.Of("step.ship.pack", facts ?? _baseFacts) with { Address = address ? Address : null, Repo = repo ? RepoName.From("name") : null };

    private static Dictionary<string, string> With(string key, string value)
    {
        var facts = new Dictionary<string, string>(_baseFacts, StringComparer.Ordinal) { [key] = value };
        return facts;
    }

    private static JsonNode Out(BlockStepResult result, string key) => JsonNode.Parse(result.Result!.Outputs[FactKey.From("fact:" + key)].GetRawText())!;

    private sealed class MaskingScrubber : ITextScrubber
    {
        public string Scrub(string text) => text.Replace("ghp_SECRET", "[redacted]", StringComparison.Ordinal);
    }

    private sealed class Rig
    {
        public InMemoryPacketDirectory Files { get; } = new();

        public InMemoryHoldoutStore Store { get; } = new();

        public FakeRunDiff Diff { get; } = new();

        public InMemoryRepoCheckouts Checkouts { get; } = new InMemoryRepoCheckouts().With("name", Checkout);

        public ITextScrubber Scrubber { get; set; } = new PassThroughScrubber();

        public Rig(string goal = "Expired links answer 410", string testChange = """[{"path":"tests/LinkTests.cs","reason":"the status changed from 404"}]""", string phaseBase = """{"rule":"default-branch","ref":"main"}""", string head = "h1")
        {
            _ = Files.Put(PacketDir, new Dictionary<string, string>(StringComparer.Ordinal)
            {
                ["packet.json"] = $$"""{"id":"demo-p1","repo":"owner/name","baseSha":"{{BaseSha}}"}""",
                ["phase.json"] = new JsonObject { ["goal"] = goal, ["kind"] = "feature", ["base"] = JsonNode.Parse(phaseBase), ["testChange"] = JsonNode.Parse(testChange) }.ToJsonString(),
                ["acceptance.json"] = """{"schemaVersion":1,"parent":"sha256:root","items":[]}""",
            });
            _ = Files.Put(ProofDir, new Dictionary<string, string>(StringComparer.Ordinal)
            {
                ["acceptance.json"] = """{"schemaVersion":1,"parent":"sha256:aa","items":[{"id":"AC-1","text":"An expired link answers 410","status":"passing","evidence":[{"kind":"api","path":"evidence/api.json","sha256":"sha256:0123456789abcdef0123456789abcdef","commit":"abcdef1234567","at":"2026-10-24T10:00:00Z"}]},{"id":"AC-2","text":"Saving twice | keeps one record","status":"failing","evidence":[]}]}""",
                ["holdout.json"] = """{"schemaVersion":1,"commit":"h1","results":[{"scenario":"H1","item":"AC-1","verdict":"pass","spent":false}]}""",
                ["not-proven.md"] = "# Not proven\n\n- AC-2 / S1 (ui): save twice\n",
                ["proof.json"] = """{"schemaVersion":1,"head":"h1","items":[],"notRun":[]}""",
            });
            _ = Files.Put(ReviewDir, new Dictionary<string, string>(StringComparer.Ordinal)
            {
                ["review.json"] = """{"schemaVersion":1,"head":"h1","verdict":"clean","round":2,"counts":{"blocking":0,"issue":0,"suggestions":3,"nits":1},"rounds":[],"findings":[]}""",
            });
            Store.Put("T-1", "demo-p1", SetText);
            Diff.Add(Tree, head);
        }

        public ShipPackStep Step() => new(Files, Checkouts, Store, Diff, Scrubber);

        public IReadOnlyDictionary<string, string> Draft() => Files.Read(InMemoryPacketDirectory.DirectoryOf(Address, "handoff"), Token).AsTask().Result.Value;
    }

    [Fact]
    public async Task A_proven_reviewed_phase_packs_into_the_runs_handoff_directory_and_reports_the_draft()
    {
        var rig = new Rig();

        var result = await rig.Step().Run(Context(), Token);

        Assert.Equal("packed", result.Result!.Outcome.Value);
        var draft = Out(result, "handoffDraft");
        Assert.Equal((InMemoryPacketDirectory.DirectoryOf(Address, "handoff"), "h1", Tree), ((string?)draft["dir"], (string?)draft["head"], (string?)draft["workspace"]));
        Assert.Equal(["body.md", "green.json", "index.json", "packet.json", "pr.json"], rig.Draft().Keys.Order(StringComparer.Ordinal), StringComparer.Ordinal);
    }

    [Fact]
    public async Task The_pull_request_file_names_the_branch_head_the_title_and_a_test_change_label()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var pr = JsonNode.Parse(rig.Draft()["pr.json"])!;
        Assert.Equal((1, "main", "sindri/demo/p1", "h1"), ((int?)pr["schemaVersion"], (string?)pr["base"], (string?)pr["headBranch"], (string?)pr["headSha"]));
        Assert.Equal(("Expired links answer 410", null), ((string?)pr["title"], (string?)pr["stackParent"]));
        Assert.Equal(["test-change"], pr["labels"]!.AsArray().Select(static l => (string?)l), StringComparer.Ordinal);
    }

    [Fact]
    public async Task A_phase_with_no_test_change_has_no_label()
    {
        var rig = new Rig(testChange: "[]");

        _ = await rig.Step().Run(Context(), Token);

        Assert.Empty(JsonNode.Parse(rig.Draft()["pr.json"])!["labels"]!.AsArray());
        Assert.DoesNotContain("Existing tests changed", rig.Draft()["body.md"], StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_stacked_phase_opens_against_its_parents_branch_and_the_body_says_so()
    {
        var rig = new Rig();
        var facts = With("phasePacket", $$"""{"hash":"sha256:phase","dir":"{{PacketDir}}","base":{"rule":"dependency-head","ref":"sindri/demo/p0"},"stackParent":"p0"}""");

        _ = await rig.Step().Run(Context(facts), Token);

        var pr = JsonNode.Parse(rig.Draft()["pr.json"])!;
        Assert.Equal(("sindri/demo/p0", "sindri/demo/p0"), ((string?)pr["base"], (string?)pr["stackParent"]));
        Assert.Contains("Stacked on `sindri/demo/p0`", rig.Draft()["body.md"], StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_branch_head_is_packed_even_when_the_proof_ran_on_an_older_one_so_freeze_can_call_it_stale()
    {
        var rig = new Rig(head: "h2");

        var result = await rig.Step().Run(Context(), Token);

        Assert.Equal("h2", (string?)Out(result, "handoffDraft")["head"]);
        Assert.Equal("h2", (string?)JsonNode.Parse(rig.Draft()["pr.json"])!["headSha"]);
    }

    [Fact]
    public async Task The_body_holds_the_acceptance_table_with_evidence_links_and_shas_and_escapes_a_pipe()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var body = rig.Draft()["body.md"];
        Assert.Contains("| AC-1 | An expired link answers 410 | passing | api `evidence/api.json` @ `abcdef1` (`sha256:0123456789abcdef`) |", body, StringComparison.Ordinal);
        Assert.Contains("| AC-2 | Saving twice \\| keeps one record | failing |", body, StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_body_holds_hidden_scenario_counts_and_verdicts_by_item_but_no_scenario_text_or_id()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var body = rig.Draft()["body.md"];
        Assert.Contains("1 hidden scenario ran: 1 passed, 0 failed, 0 spent.", body, StringComparison.Ordinal);
        Assert.Contains("- AC-1: pass", body, StringComparison.Ordinal);
        Assert.DoesNotContain("H1", body, StringComparison.Ordinal);
        Assert.DoesNotContain("expired link\"", body, StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_body_holds_not_proven_the_review_rounds_the_test_changes_and_a_footer_with_the_hashes()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var body = rig.Draft()["body.md"];
        Assert.Contains("- AC-2 / S1 (ui): save twice", body, StringComparison.Ordinal);
        Assert.Contains("clean after 2 rounds: 0 blocking, 0 issue, 3 suggestions, 1 nit.", body, StringComparison.Ordinal);
        Assert.Contains("- `tests/LinkTests.cs`: the status changed from 404", body, StringComparison.Ordinal);
        Assert.Contains("Line `demo`, phase `p1`, attempt 1", body, StringComparison.Ordinal);
        Assert.Contains("phase packet `sha256:phase`, proof `sha256:proof`, review `sha256:review`", body, StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_proof_with_nothing_skipped_says_so()
    {
        var rig = new Rig();
        _ = rig.Files.Put(ProofDir, new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["acceptance.json"] = """{"schemaVersion":1,"parent":"sha256:aa","items":[]}""",
            ["holdout.json"] = """{"schemaVersion":1,"commit":"h1","results":[]}""",
            ["not-proven.md"] = "nothing skipped\n",
            ["proof.json"] = """{"schemaVersion":1,"head":"h1","items":[],"notRun":[]}""",
        });

        _ = await rig.Step().Run(Context(), Token);

        Assert.Contains("Nothing skipped.", rig.Draft()["body.md"], StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_packet_names_the_handoff_kind_and_its_links_and_the_index_chains_proof_and_review()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var packet = JsonNode.Parse(rig.Draft()["packet.json"])!;
        Assert.Equal((1, "handoff", "demo-p1-handoff", "owner/name", BaseSha, "draft"), ((int?)packet["schemaVersion"], (string?)packet["kind"], (string?)packet["id"], (string?)packet["repo"], (string?)packet["baseSha"], (string?)packet["status"]));
        Assert.Null(packet["hash"]);
        Assert.Equal(["pr.json", "body.md", "green.json", "index.json"], _linkKeys.Select(k => (string?)packet["links"]![k]), StringComparer.Ordinal);
        var index = JsonNode.Parse(rig.Draft()["index.json"])!;
        Assert.Equal(["sha256:proof", "sha256:review"], index["parents"]!.AsArray().Select(static p => (string?)p), StringComparer.Ordinal);
        Assert.Null(index["acceptance"]!["self"]);
        Assert.Equal(ProofPack.Sha256("""{"schemaVersion":1,"parent":"sha256:aa","items":[{"id":"AC-1","text":"An expired link answers 410","status":"passing","evidence":[{"kind":"api","path":"evidence/api.json","sha256":"sha256:0123456789abcdef0123456789abcdef","commit":"abcdef1234567","at":"2026-10-24T10:00:00Z"}]},{"id":"AC-2","text":"Saving twice | keeps one record","status":"failing","evidence":[]}]}"""), (string?)index["acceptance"]!["extends"]);
    }

    [Fact]
    public async Task The_green_file_records_the_head_and_the_commands_the_local_gate_ran()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(), Token);

        var green = JsonNode.Parse(rig.Draft()["green.json"])!;
