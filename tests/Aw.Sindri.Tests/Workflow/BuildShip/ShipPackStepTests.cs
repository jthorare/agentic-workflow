    [Fact]
    public async Task Without_a_line_the_branch_is_named_for_the_packet()
    {
        var rig = new Rig();

        _ = await rig.Step().Run(Context(With("lineContext", "{}")), Token);

        Assert.Equal("sindri/demo-p1", (string?)JsonNode.Parse(rig.Draft()["pr.json"])!["headBranch"]);
        Assert.Contains("Phase `demo-p1`", rig.Draft()["body.md"], StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_title_and_the_body_pass_the_scrubber()
    {
        var rig = new Rig(goal: "Use ghp_SECRET for the link check") { Scrubber = new MaskingScrubber() };

        _ = await rig.Step().Run(Context(), Token);

        Assert.Equal("Use [redacted] for the link check", (string?)JsonNode.Parse(rig.Draft()["pr.json"])!["title"]);
        Assert.DoesNotContain("ghp_SECRET", rig.Draft()["body.md"], StringComparison.Ordinal);
    }

    [Fact]
    public async Task A_title_over_72_characters_is_cut_at_a_word_with_an_ellipsis_and_only_the_first_line_is_used()
    {
        var rig = new Rig(goal: "Expired links answer 410 and the export page says why the link is gone and how to ask for a new one\nSecond line");

        _ = await rig.Step().Run(Context(), Token);

        var title = (string?)JsonNode.Parse(rig.Draft()["pr.json"])!["title"];
        Assert.True(title!.Length <= 72, title);
        Assert.EndsWith("...", title, StringComparison.Ordinal);
        Assert.DoesNotContain("Second", title, StringComparison.Ordinal);
    }

    [Fact]
    public async Task The_canary_phrase_in_the_body_fails_the_Step_names_the_rule_and_writes_nothing()
    {
        var rig = new Rig(goal: $"Mention {Canary} here");

        var result = await rig.Step().Run(Context(), Token);

        Assert.Null(result.Result);
        Assert.Contains("PRV-HOLD-003", result.Failure, StringComparison.Ordinal);
        Assert.DoesNotContain(Canary, result.Failure, StringComparison.OrdinalIgnoreCase);
        Assert.True((await rig.Files.Read(InMemoryPacketDirectory.DirectoryOf(Address, "handoff"), Token)).IsError);
    }

    [Fact]
    public async Task A_phase_with_no_hidden_set_fails_the_Step_since_the_canary_cannot_be_scanned()
    {
        var rig = new Rig();
        rig.Store.Put("T-1", "demo-p1", setText: null);

        var result = await rig.Step().Run(Context(), Token);

        Assert.Null(result.Result);
        Assert.Contains("canary", result.Failure, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("phasePacket")]
    [InlineData("proofPack")]
