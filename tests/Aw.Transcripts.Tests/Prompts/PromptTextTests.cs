using Aw.Transcripts.Core.Prompts;

namespace Aw.Transcripts.Tests.Prompts;

public sealed class PromptTextTests
{
    [Theory, Trait("Lane", "unit")]
    [InlineData("fix the login bug")]
    [InlineData("  no, use the other table\n")]
    [InlineData("<pasted_content>a pasted log</pasted_content> what broke?")]
    public void Typed_text_is_a_prompt(string text) => Assert.True(PromptText.IsTyped(text));

    [Theory, Trait("Lane", "unit")]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData("<system-reminder>context</system-reminder>")]
    [InlineData("<command-name>/review</command-name>\n<command-message>review</command-message>")]
    [InlineData("<local-command-stdout>ok</local-command-stdout>")]
    [InlineData("<teammate-message teammate_id=\"lead\">do the thing</teammate-message>")]
    [InlineData("<task-notification>done</task-notification>")]
    [InlineData("<environment_context>cwd</environment_context>")]
    [InlineData("This session is being continued from a previous conversation that ran out of context.")]
    [InlineData("Base directory for this skill: /skills/x")]
    [InlineData("Caveat: The messages below were generated by the user while running local commands.")]
    [InlineData("Another Claude session sent a message: hi")]
    [InlineData("[Request interrupted by user]")]
    [InlineData("# AGENTS.md instructions for /work/alpha")]
    public void Harness_text_is_not_a_prompt(string text) => Assert.False(PromptText.IsTyped(text));

    [Theory, Trait("Lane", "unit")]
    [InlineData("<ide_opened_file>The user opened src/a.cs in the IDE.</ide_opened_file> fix the null check", "fix the null check")]
    [InlineData("<ide_selection>The user selected lines 3-9.</ide_selection>\nexplain this", "explain this")]
    [InlineData("<ide_opened_file>a</ide_opened_file>\n<ide_selection>b</ide_selection>\nboth blocks", "both blocks")]
    public void Text_typed_after_ide_blocks_is_a_prompt_without_the_blocks(string text, string typed)
    {
        Assert.True(PromptText.IsTyped(text));
        Assert.Equal(typed, PromptText.WithoutIdeBlocks(text));
    }

    [Theory, Trait("Lane", "unit")]
    [InlineData("<ide_opened_file>The user opened src/a.cs in the IDE.</ide_opened_file>")]
    [InlineData("<ide_selection>lines 3-9</ide_selection>\n  ")]
    [InlineData("<ide_opened_file>a</ide_opened_file><system-reminder>context</system-reminder>")]
    [InlineData("<ide_unknown>a</ide_unknown> fix it")]
    [InlineData("<editor_state>a</editor_state> fix it")]
    public void Ide_blocks_with_nothing_typed_after_them_or_another_tag_stay_machine_text(string text) => Assert.False(PromptText.IsTyped(text));

    [Fact, Trait("Lane", "unit")]
    public void Leading_tag_blocks_are_stripped_and_an_unclosed_one_stays()
    {
        Assert.Equal("the prompt", PromptText.StripLeadingTagBlocks("<a>x</a>\n<b x=\"1\">y</b> the prompt"));
        Assert.Equal("<a>never closed", PromptText.StripLeadingTagBlocks("<a>never closed"));
    }

    [Fact, Trait("Lane", "unit")]
    public void A_cursor_prompt_is_its_user_query_text()
    {
        Assert.Equal("fix it\nand the tests", CursorPrompt.Body("<timestamp>x</timestamp><user_query>\nfix it\n</user_query><user_query>and the tests</user_query>"));
        Assert.Equal("plain", CursorPrompt.Body("<attached_files>a</attached_files>\nplain"));
    }

    [Theory, Trait("Lane", "unit")]
    [InlineData("<timestamp>Thursday, Sep 3, 2026, 4:45 PM (UTC-7)</timestamp>", "2026-09-03T23:45:00+00:00")]
    [InlineData("<timestamp>Sep 3, 2026, 12:05 AM (UTC)</timestamp>", "2026-09-03T00:05:00+00:00")]
    [InlineData("<timestamp>Monday, November 2, 2026, 9:30 am (UTC+5:30)</timestamp>", "2026-11-02T04:00:00+00:00")]
    public void A_cursor_timestamp_block_reads_as_utc(string text, string expected) =>
        Assert.Equal(DateTimeOffset.Parse(expected, System.Globalization.CultureInfo.InvariantCulture), CursorPrompt.Timestamp(text));

    [Theory, Trait("Lane", "unit")]
    [InlineData("no block")]
    [InlineData("<timestamp>yesterday</timestamp>")]
    [InlineData("<timestamp>Sep 3, 2026, 4:45 PM (UTC+19)</timestamp>")]
    public void An_unreadable_cursor_timestamp_is_null(string text) => Assert.Null(CursorPrompt.Timestamp(text));
}
